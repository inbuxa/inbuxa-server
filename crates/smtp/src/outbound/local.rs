impl MessageWrapper {
    pub(super) async fn deliver_local(
        &self,
        rcpt_idxs: &[usize],
        statuses: &mut Vec<DeliveryResult>,
        server: &Server,
    ) {
        // Prepare recipients list
        let mut pending_recipients = Vec::new();
        let mut recipients = Vec::new();
        for &rcpt_idx in rcpt_idxs {
            let rcpt = &self.message.recipients[rcpt_idx];
            let rcpt_addr = rcpt.address();
            recipients.push(IngestRecipient {
                address: rcpt_addr.to_lowercase(),
                orcpt: rcpt.orcpt.as_ref().map(|orcpt| orcpt.to_string()),
                spam_percentage: rcpt_spam_percentage(rcpt.flags),
            });
            pending_recipients.push((rcpt_idx, rcpt_addr));
        }

        // Deliver message
        let delivery_result = server
            .deliver_message(IngestMessage {
                sender_address: self.message.return_path.to_string(),
                sender_authentication: if self.message.flags & FROM_AUTHENTICATED != 0 {
                    SenderAuthentication::Submission
                } else if self.message.flags & FROM_UNAUTHENTICATED_DMARC != 0 {
                    SenderAuthentication::DmarcPass
                } else {
                    SenderAuthentication::Unauthenticated
                },
                recipients,
                message_blob: self.message.blob_hash.clone(),
                message_size: self.message.size,
                session_id: self.span_id,
            })
            .await;

        // Process delivery results
        for ((rcpt_idx, rcpt_addr), result) in
            pending_recipients.into_iter().zip(delivery_result.status)
        {
            let status = match result {
                LocalDeliveryStatus::Success => Status::Completed(Box::new(HostResponse {
                    hostname: "localhost".into(),
                    response: Response {
                        code: 250,
                        esc: [2, 1, 5],
                        message: "OK".into(),
                    },
                })),
                LocalDeliveryStatus::TemporaryFailure { reason } => {
                    Status::TemporaryFailure(Box::new(ErrorDetails {
                        entity: "localhost".into(),
                        details: Error::UnexpectedResponse(Box::new(UnexpectedResponse {
                            command: format!("RCPT TO:<{rcpt_addr}>").into_boxed_str(),
                            response: Response {
                                code: 451,
                                esc: [4, 3, 0],
                                message: reason.into(),
                            },
                        })),
                    }))
                }
                LocalDeliveryStatus::PermanentFailure { code, reason } => {
                    Status::PermanentFailure(Box::new(ErrorDetails {
                        entity: "localhost".into(),
                        details: Error::UnexpectedResponse(Box::new(UnexpectedResponse {
                            command: format!("RCPT TO:<{rcpt_addr}>").into_boxed_str(),
                            response: Response {
                                code: 550,
                                esc: code,
                                message: reason.into(),
                            },
                        })),
                    }))
                }
            };
            statuses.push(DeliveryResult::account(status, rcpt_idx));
        }

        // Process autogenerated messages
        for autogenerated in delivery_result.autogenerated {
            let return_path = match autogenerated.return_path {
                AutogeneratedReturnPath::Account => autogenerated.account_address.as_str(),
                AutogeneratedReturnPath::Null => "",
            };
            let mut message =
                server.new_message(return_path, MessageSource::Autogenerated, self.span_id);
            for rcpt in autogenerated.recipients {
                message.expand_and_add_recipient(rcpt, server).await;
            }
            let flags = notify_flags(&autogenerated.notify);
            if flags != 0 {
                for rcpt in &mut message.message.recipients {
                    rcpt.flags |= flags;
                }
            }

            // Queue Message
            message.message.size = autogenerated.message.len() as u64;
            let quotas = server.queue_quotas(&message).await;
            let dkim_signers = server
                .eval_signers(
                    &server.core.sieve.untrusted_sign,
                    &AutogeneratedSigner {
                        message: &message.message,
                        account_address: &autogenerated.account_address,
                    },
                    self.span_id,
                )
                .await;

            let auth_message = if dkim_signers
                .as_ref()
                .is_some_and(|signers| signers.dkim2.is_some())
                && has_dkim2_headers(&autogenerated.message)
                && server
                    .has_remote_domain(
                        message
                            .message
                            .recipients
                            .iter()
                            .map(|rcpt| rcpt.domain_part()),
                    )
                    .await
            {
                AuthenticatedMessage::parse(&autogenerated.message)
            } else {
                None
            };
            let dkim2_verified = match &auth_message {
                Some(auth_message) => {
                    server
                        .dkim2_signing_proof(
                            dkim_signers.as_deref(),
                            auth_message,
                            &self.message.return_path,
                            rcpt_idxs
                                .iter()
                                .filter_map(|&rcpt_idx| self.message.recipients.get(rcpt_idx))
                                .map(|rcpt| rcpt.address()),
                        )
                        .await
                }
                None => None,
            };

            if message
                .queue(
                    QueueParams::new(&autogenerated.message, self.span_id, server)
                        .with_dkim_signers(dkim_signers)
                        .with_dkim2_verified(dkim2_verified.as_ref())
                        .with_exploded(autogenerated.exploded)
                        .with_quotas(quotas),
                )
                .await
                == QueueOutcome::QuotaExceeded
            {
                trc::event!(Sieve(SieveEvent::QuotaExceeded), SpanId = self.span_id);
            }
        }
    }
}

struct AutogeneratedSigner<'x> {
    message: &'x Message,
    account_address: &'x str,
}

impl ResolveVariable for AutogeneratedSigner<'_> {
    fn resolve_variable<'a>(
        &'a self,
        variable: ExpressionVariable,
        arena: &'a Bump,
    ) -> Variable<'a> {
        match variable {
            ExpressionVariable::Sender => self.account_address.into(),
            ExpressionVariable::SenderDomain => self.account_address.domain_part().into(),
            _ => self.message.resolve_variable(variable, arena),
        }
    }
}
